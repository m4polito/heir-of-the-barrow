// Original 8x8 bitmap font. X = lit, . = off. Column 7 is always blank (letter gap).
// Caps/digits fill rows 0-6; lowercase x-height is rows 2-6; descenders reach row 7.

/** Build an 8x8 glyph: `rows` start at row `top`, each right-padded to 8 columns. */
function g(top: number, rows: string[]): string[] {
  const out: string[] = [];
  for (let r = 0; r < 8; r++) {
    const row = rows[r - top] ?? '';
    out.push(row.padEnd(8, '.'));
  }
  return out;
}

